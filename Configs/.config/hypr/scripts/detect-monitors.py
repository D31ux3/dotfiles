#!/usr/bin/env python3
# Adds a rule to conf/monitors_local.lua for each connected monitor that has none yet,
# with the mode, position and scale it is using now. Edit that file to configure each one.
# Monitors are matched by description (brand, model, serial), so a rule follows the
# screen whatever port it is plugged into. The file is per machine and not versioned.
# Runs on Hyprland start and when a monitor is plugged in (conf/autostart.lua).

import json
import os
import subprocess

RULES = os.path.expanduser("~/.config/hypr/conf/monitors_local.lua")
HEADER = """\
-- Per-monitor rules for this machine, generated by scripts/detect-monitors.py (not versioned).
-- Edit them freely: monitors already here are never touched again.
-- Delete a block to detect that monitor again. Options: https://wiki.hypr.land/Configuring/Basics/Monitors/
"""


def lua_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def rule(monitor):
    output = lua_string("desc:" + monitor["description"])
    return f"""
-- {monitor["name"]} · available: {" ".join(monitor["availableModes"])}
hl.monitor({{
    output   = {output},
    mode     = "{monitor["width"]}x{monitor["height"]}@{monitor["refreshRate"]:.2f}",
    position = "{monitor["x"]}x{monitor["y"]}",
    scale    = {monitor["scale"]:g},
}})
"""


monitors = json.loads(subprocess.run(
    ["hyprctl", "monitors", "all", "-j"], capture_output=True, text=True, check=True
).stdout)

try:
    with open(RULES) as f:
        current = f.read()
except FileNotFoundError:
    current = HEADER

new = [m for m in monitors
       if not m["disabled"] and lua_string("desc:" + m["description"]) not in current]

if new:
    with open(RULES, "w") as f:
        f.write(current + "".join(rule(m) for m in new))
    subprocess.run(["hyprctl", "reload"], stdout=subprocess.DEVNULL)
    names = ", ".join(m["name"] for m in new)
    subprocess.run(["notify-send", "Monitors", f"Detected {names}. Configure in ~/.config/hypr/conf/monitors_local.lua"])
